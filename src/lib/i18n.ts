export const locales = ['th', 'en'] as const
export type Locale = (typeof locales)[number]

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value)
}

/** path ของภาษานั้น — ไทยไม่มี prefix, อังกฤษขึ้นต้น /en */
export function lp(locale: Locale, path: string) {
  const clean = path.startsWith('/') ? path : `/${path}`
  if (locale === 'th') return clean
  return clean === '/' ? '/en' : `/en${clean}`
}

/** เลือกคอลัมน์ตามภาษา เช่น pick(row, 'title', 'en') → title_en ถ้าไม่มีใช้ title_th */
export function pick<T extends Record<string, unknown>>(row: T, base: string, locale: Locale): string {
  const th = (row[`${base}_th`] as string | null) ?? ''
  const en = (row[`${base}_en`] as string | null) ?? ''
  return locale === 'en' ? en || th : th || en
}

